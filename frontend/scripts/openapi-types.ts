// Generates src/lib/api/types.d.ts, the `paths`/`components`/`operations` declarations that
// openapi-fetch consumes, from the backend's OpenAPI 3.1 document.
//
//   bun scripts/openapi-types.ts <schema file or URL> <output .d.ts>
//
// It replaces openapi-typescript 7.13.0, which builds its output with the TypeScript compiler
// API: its `typescript ^5.x` peer excludes the frontend's TypeScript 6, and TypeScript 7's
// package has no compiler API at all. This emits text directly and needs no TypeScript.
//
// For the OpenAPI subset Litestar emits, the output below the header is byte-identical to
// openapi-typescript 7.13.0 with default options, down to the TypeScript printer's layout,
// parentheses and JSDoc (scripts/fixtures/openapi-types holds its verbatim output for an
// edge-case schema). Anything outside that subset throws instead of producing a guessed type.

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

type Member =
	| {
			kind: 'property';
			name: string;
			optional: boolean;
			readonly: boolean;
			type: TypeNode;
			doc?: string;
	  }
	| { kind: 'index'; parameter: string; type: TypeNode };

type TypeNode =
	| { kind: 'keyword'; name: 'string' | 'number' | 'boolean' | 'unknown' | 'never' | 'null' }
	| { kind: 'literal'; text: string }
	| { kind: 'reference'; text: string }
	| { kind: 'array'; element: TypeNode }
	| { kind: 'union' | 'intersection'; types: TypeNode[] }
	| { kind: 'object'; members: Member[] };

const keyword = (name: Extract<TypeNode, { kind: 'keyword' }>['name']): TypeNode => ({
	kind: 'keyword',
	name
});
const STRING = keyword('string');
const NUMBER = keyword('number');
const BOOLEAN = keyword('boolean');
const UNKNOWN = keyword('unknown');
const NEVER = keyword('never');
const NULL = keyword('null');
const RECORD_NEVER: TypeNode = { kind: 'reference', text: 'Record<string, never>' };

const METHODS = ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace'] as const;
const PARAMETER_LOCATIONS = ['query', 'header', 'path', 'cookie'] as const;
const IDENTIFIER = /^[A-Za-z_$][A-Za-z_$0-9]*$/;

// Keywords openapi-typescript understands but Litestar never emits; refuse them instead of
// silently dropping their meaning.
const UNSUPPORTED_SCHEMA_KEYWORDS = [
	'allOf',
	'discriminator',
	'prefixItems',
	'patternProperties',
	'$defs'
];

export const HEADER = `/**
 * This file was auto-generated by scripts/openapi-types.ts from the backend's OpenAPI schema.
 * Do not make direct changes to the file.
 */

`;

function isObject(value: Json | undefined): value is JsonObject {
	return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function fail(path: string, message: string): never {
	throw new Error(`${path}: ${message}`);
}

function escapePointer(part: string): string {
	return part.replace(/~/g, '~0').replace(/\//g, '~1');
}

function child(path: string, ...parts: string[]): string {
	return parts.reduce((pointer, part) => `${pointer}/${escapePointer(part)}`, path);
}

function refPointer(ref: string, path: string): string[] {
	const [uri, pointer = ''] = ref.split('#/');
	if (uri) fail(path, `external $ref ${ref} is not supported`);
	const parts = pointer
		.split('/')
		.map((part) => decodeURIComponent(part.replace(/~1/g, '/').replace(/~0/g, '~')))
		.filter(Boolean);
	if (parts.length === 0) fail(path, `invalid $ref ${ref}`);
	return parts;
}

function reference(ref: string, path: string): TypeNode {
	const [root, ...rest] = refPointer(ref, path);
	let text = root as string;
	for (const [index, segment] of rest.entries()) {
		if (index >= 2 && segment === 'properties') continue;
		text += `[${JSON.stringify(segment)}]`;
	}
	return { kind: 'reference', text };
}

// openapi-typescript bundled the document with Redocly first, which rejects a dangling $ref.
function assertResolves(document: JsonObject, ref: string, path: string): void {
	let node: Json = document;
	for (const part of refPointer(ref, path)) {
		if (!isObject(node) || !(part in node)) fail(path, `cannot resolve $ref ${ref}`);
		node = node[part] as Json;
	}
}

function propertyName(name: string): string {
	if (String(Number(name)) === name && name[0] !== '-') return name;
	return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}

// openapi-typescript's JSDoc: title, summary, format, @deprecated, @description, @default,
// @example (also each entry of an `examples` array), @constant and @enum, in that order.
function jsDoc(node: Json | undefined): string | undefined {
	if (!isObject(node)) return undefined;
	const indent = (text: string) => text.trim().replace(/\r?\n/g, '\n *     ');
	const serialize = (value: Json) =>
		indent(
			typeof value === 'object' && value !== null ? JSON.stringify(value, null, 2) : String(value)
		);
	const lines: string[] = [];
	if (typeof node.title === 'string' && node.title) lines.push(indent(node.title));
	if (typeof node.summary === 'string' && node.summary) lines.push(indent(node.summary));
	if (node.format) lines.push(`Format: ${String(node.format)}`);
	if (node.deprecated) lines.push('@deprecated');
	for (const field of ['description', 'default', 'example'] as const) {
		const value = node[field];
		if (value === undefined || (value === '' && field === 'description')) continue;
		lines.push(`@${field} ${serialize(value)}`);
	}
	if (Array.isArray(node.examples)) {
		for (const example of node.examples) lines.push(`@example ${serialize(example)}`);
	}
	if ('const' in node) lines.push('@constant');
	if (node.enum) {
		const type = Array.isArray(node.type)
			? node.type.join('|')
			: typeof node.type === 'string'
				? node.type
				: 'unknown';
		lines.push(`@enum {${type}${node.nullable ? '|null' : ''}}`);
	}
	if (lines.length === 0) return undefined;
	const text =
		lines.length === 1 && !lines[0]?.includes('\n')
			? `* ${lines[0]} `
			: `*\n * ${lines.join('\n * ')}\n `;
	// The printer drops whitespace at the end of a comment line.
	return `/*${text.replace(/\*\//g, '*\\/').replace(/[ \t]+\n/g, '\n')}*/`;
}

// openapi-typescript drops a repeated primitive keyword (not `unknown`) from unions and
// intersections; literals and references are kept as written.
function dedupe(types: TypeNode[]): TypeNode[] {
	const seen = new Set<string>();
	return types.filter((type) => {
		if (type.kind !== 'keyword' || type.name === 'unknown') return true;
		if (seen.has(type.name)) return false;
		seen.add(type.name);
		return true;
	});
}

function union(types: TypeNode[]): TypeNode {
	if (types.length === 0) return NEVER;
	if (types.length === 1) return types[0] as TypeNode;
	return { kind: 'union', types: dedupe(types) };
}

function intersection(types: TypeNode[]): TypeNode {
	if (types.length === 0) return NEVER;
	if (types.length === 1) return types[0] as TypeNode;
	return { kind: 'intersection', types: dedupe(types) };
}

function isPrimitive(type: TypeNode): boolean {
	return type.kind === 'keyword' && type.name !== 'unknown';
}

function literal(value: Json, path: string): TypeNode {
	if (typeof value === 'string') return { kind: 'literal', text: JSON.stringify(value) };
	if (typeof value === 'number' || typeof value === 'boolean') {
		return { kind: 'literal', text: String(value) };
	}
	if (value === null) return NULL;
	return fail(path, 'only primitive enum and const values are supported');
}

function property(
	name: string,
	type: TypeNode,
	options: { optional?: boolean; readonly?: boolean; doc?: Json } = {}
): Member {
	return {
		kind: 'property',
		name,
		optional: options.optional ?? false,
		readonly: options.readonly ?? false,
		type,
		doc: jsDoc(options.doc)
	};
}

class Generator {
	readonly operations: Member[] = [];

	constructor(readonly document: JsonObject) {}

	reference(ref: string, path: string): TypeNode {
		assertResolves(this.document, ref, path);
		return reference(ref, path);
	}

	schema(node: Json | undefined, path: string): TypeNode {
		if (node === undefined || node === false || node === null) return NEVER;
		if (node === true) return UNKNOWN;
		if (!isObject(node)) return fail(path, 'expected a schema object');
		if (typeof node.$ref === 'string') return this.reference(node.$ref, path);
		for (const key of UNSUPPORTED_SCHEMA_KEYWORDS) {
			if (key in node && node[key] !== false) fail(path, `schema keyword ${key} is not supported`);
		}
		if (node.const !== undefined && node.const !== null) return literal(node.const, path);
		if (
			Array.isArray(node.enum) &&
			node.type !== 'object' &&
			!('properties' in node) &&
			!('additionalProperties' in node)
		) {
			const members = node.enum.map((value) => literal(value, path));
			if ((Array.isArray(node.type) && node.type.includes('null')) || node.nullable) {
				members.push(NULL);
			}
			return union(members);
		}
		const core = this.core(node, path);
		let type: TypeNode | undefined = core;
		const anyOf = Array.isArray(node.anyOf) ? node.anyOf : [];
		if (anyOf.length) {
			const members = anyOf.map((item, index) =>
				this.schema(item, child(path, 'anyOf', String(index)))
			);
			type = union([...(type ? [type] : []), ...members]);
		}
		const oneOf = Array.isArray(node.oneOf)
			? node.oneOf
			: node.type === 'object' && Array.isArray(node.enum)
				? node.enum
				: [];
		if (oneOf.length) {
			const members = oneOf.map((item, index) =>
				this.schema(item, child(path, 'oneOf', String(index)))
			);
			type = members.every(isPrimitive)
				? union([...(type ? [type] : []), ...members])
				: intersection([...(type ? [type] : []), union(members)]);
		}
		type ??= 'type' in node ? RECORD_NEVER : UNKNOWN;
		if (type !== UNKNOWN && node.nullable) type = { kind: 'union', types: [type, NULL] };
		return type;
	}

	core(node: JsonObject, path: string): TypeNode | undefined {
		const type = node.type;
		if (type) {
			if (type === 'null') return NULL;
			if (type === 'string') return STRING;
			if (type === 'number' || type === 'integer') return NUMBER;
			if (type === 'boolean') return BOOLEAN;
			if (type === 'array') {
				if (Array.isArray(node.items)) fail(path, 'tuple items are not supported');
				// As in openapi-typescript: array items are wrapped once more, and an item type that
				// is already an array is not wrapped again.
				let items = node.items === undefined ? UNKNOWN : this.schema(node.items, path);
				if (isObject(node.items) && node.items.type === 'array')
					items = { kind: 'array', element: items };
				return items.kind === 'array' ? items : { kind: 'array', element: items };
			}
			if (Array.isArray(type)) {
				const oneOf = Array.isArray(node.oneOf) ? node.oneOf : undefined;
				const members: TypeNode[] = [];
				for (const member of type) {
					if (member === 'null' || member === null) {
						if (!oneOf?.some((item) => isObject(item) && item.type === 'null')) members.push(NULL);
						continue;
					}
					const scalar = ['boolean', 'string', 'number', 'integer'].includes(String(member));
					if (oneOf && scalar && oneOf.some((item) => isObject(item) && item.type === member))
						continue;
					members.push(
						this.schema({ ...node, type: member, ...(oneOf ? { oneOf: null } : {}) }, path)
					);
				}
				return union(members);
			}
		}
		const properties = isObject(node.properties) ? Object.entries(node.properties) : [];
		const additional = node.additionalProperties;
		if (!properties.length && !additional) return undefined;
		const required = Array.isArray(node.required) ? node.required : [];
		const members: Member[] = [];
		for (const [name, value] of properties) {
			if (!isObject(value) && typeof value !== 'boolean') {
				fail(path, `invalid property ${name}`);
			}
			const hasDefault = isObject(value) && value.default !== undefined;
			const optional = !(
				required.includes(name) ||
				(hasDefault && !path.includes('parameters') && !path.includes('requestBody'))
			);
			const memberType =
				isObject(value) && typeof value.$ref === 'string'
					? this.reference(value.$ref, path)
					: this.schema(value, child(path, name));
			// Without openapi-typescript's read/write markers, readOnly is a readonly modifier and
			// writeOnly has no effect.
			const readonly = isObject(value) && Boolean(value.readOnly);
			members.push(property(name, memberType, { optional, readonly, doc: value }));
		}
		const explicit = isObject(additional) && Object.keys(additional).length > 0;
		const implicit =
			additional === true || (isObject(additional) && Object.keys(additional).length === 0);
		const indexTypes: TypeNode[] = [];
		if (explicit) indexTypes.push(this.schema(additional, path));
		if (implicit) indexTypes.push(UNKNOWN);
		const object: TypeNode | undefined = members.length ? { kind: 'object', members } : undefined;
		if (!indexTypes.length) return object;
		return intersection([
			...(object ? [object] : []),
			{ kind: 'object', members: [{ kind: 'index', parameter: 'key', type: union(indexTypes) }] }
		]);
	}

	parameters(parameters: Json[], path: string): Member {
		const resolved = parameters.map((parameter) => {
			if (!isObject(parameter)) return fail(path, 'expected a parameter object');
			if (typeof parameter.$ref === 'string') fail(path, 'parameter $ref is not supported');
			return parameter;
		});
		const locations = PARAMETER_LOCATIONS.map((location) => {
			const members = resolved
				.filter((parameter) => parameter.in === location)
				.map((parameter) =>
					property(
						String(parameter.name),
						parameter.schema === undefined
							? STRING
							: this.schema(
									parameter.schema,
									child(path, 'parameters', location, String(parameter.name))
								),
						{ optional: location !== 'path' && !parameter.required, doc: parameter }
					)
				);
			const allOptional = members.every((member) => member.kind === 'property' && member.optional);
			return property(location, members.length ? { kind: 'object', members } : NEVER, {
				optional: allOptional
			});
		});
		return property('parameters', { kind: 'object', members: locations });
	}

	content(content: Json | undefined, path: string): Member[] {
		if (content === undefined) return [];
		if (!isObject(content)) return fail(path, 'expected a content map');
		return Object.entries(content).map(([mediaType, media]) => {
			if (!isObject(media)) return fail(path, `invalid media type ${mediaType}`);
			if (typeof media.$ref === 'string') fail(path, 'media type $ref is not supported');
			const type =
				media.schema === undefined
					? UNKNOWN
					: this.schema(media.schema, child(path, 'content', mediaType));
			return property(mediaType, type, { doc: media });
		});
	}

	response(response: JsonObject, path: string): TypeNode {
		const headers: Member[] = [];
		if (isObject(response.headers)) {
			for (const [name, header] of Object.entries(response.headers)) {
				if (!isObject(header) || typeof header.$ref === 'string' || header.content !== undefined) {
					fail(path, `header ${name} must be an inline schema header`);
				}
				const type =
					header.schema === undefined
						? UNKNOWN
						: this.schema(header.schema, child(path, 'headers', name));
				headers.push(property(name, type, { optional: !header.required, doc: header }));
			}
		}
		headers.push({ kind: 'index', parameter: 'name', type: UNKNOWN });
		const content = this.content(response.content, path);
		return {
			kind: 'object',
			members: [
				property('headers', { kind: 'object', members: headers }),
				content.length
					? property('content', { kind: 'object', members: content })
					: property('content', NEVER, { optional: true })
			]
		};
	}

	operation(operation: JsonObject, parameters: Json[], path: string): Member[] {
		const members = [this.parameters(parameters, path)];
		const body = operation.requestBody;
		if (body === undefined) {
			members.push(property('requestBody', NEVER, { optional: true }));
		} else {
			if (!isObject(body) || typeof body.$ref === 'string') {
				fail(path, 'requestBody must be inline');
			}
			const content = this.content(body.content, child(path, 'requestBody'));
			const contentType: TypeNode = {
				kind: 'object',
				members: content.length ? content : [property('*/*', NEVER, { optional: true })]
			};
			members.push(
				property(
					'requestBody',
					{ kind: 'object', members: [property('content', contentType)] },
					{
						optional: !body.required,
						doc: body
					}
				)
			);
		}
		const responses = isObject(operation.responses) ? Object.entries(operation.responses) : [];
		const responseMembers = responses.map(([code, response]) => {
			if (!isObject(response) || typeof response.$ref === 'string') {
				fail(path, `response ${code} must be inline`);
			}
			return property(code, this.response(response, child(path, 'responses', code)), {
				doc: response
			});
		});
		members.push(
			property(
				'responses',
				responseMembers.length ? { kind: 'object', members: responseMembers } : NEVER
			)
		);
		return members;
	}

	pathItem(item: JsonObject, path: string): TypeNode {
		const shared = Array.isArray(item.parameters) ? item.parameters : [];
		const members = [this.parameters(shared, child(path, 'parameters'))];
		for (const method of METHODS) {
			const operation = item[method];
			if (operation === undefined) {
				members.push(property(method, NEVER, { optional: true }));
				continue;
			}
			if (!isObject(operation) || typeof operation.$ref === 'string') {
				fail(path, `${method} must be an inline operation`);
			}
			if (typeof operation.operationId !== 'string') fail(path, `${method} needs an operationId`);
			// Path-level parameters first; an operation parameter with the same location and name
			// replaces it in place.
			const keyed = new Map<string, Json>();
			const own = Array.isArray(operation.parameters) ? operation.parameters : [];
			for (const parameter of [...shared, ...own]) {
				if (!isObject(parameter)) fail(path, 'expected a parameter object');
				keyed.set(`${String(parameter.in)}-${String(parameter.name)}`, parameter);
			}
			const id = operation.operationId.replace(/#/g, '/');
			this.operations.push(
				property(id, {
					kind: 'object',
					members: this.operation(operation, [...keyed.values()], child(path, method))
				})
			);
			members.push(
				property(method, reference(`#/operations/${escapePointer(id)}`, path), { doc: operation })
			);
		}
		return { kind: 'object', members };
	}

	generate(): string {
		const document = this.document;
		if (typeof document.openapi !== 'string' || !document.openapi.startsWith('3.')) {
			fail('#', 'expected an OpenAPI 3 document');
		}
		const ids = new Set<string>();
		const paths: Member[] = [];
		for (const [url, item] of Object.entries(isObject(document.paths) ? document.paths : {})) {
			if (!isObject(item)) continue;
			if (typeof item.$ref === 'string')
				fail(child('#/paths', url), 'path item $ref is not supported');
			for (const method of METHODS) {
				const id = isObject(item[method]) ? item[method].operationId : undefined;
				if (typeof id !== 'string') continue;
				if (ids.has(id)) fail(child('#/paths', url), `duplicate operationId ${id}`);
				ids.add(id);
			}
			paths.push(property(url, this.pathItem(item, child('#/paths', url))));
		}
		if (isObject(document.$defs) && Object.keys(document.$defs).length) {
			fail('#/$defs', 'top-level $defs are not supported');
		}
		const components = isObject(document.components) ? document.components : undefined;
		const schemas =
			components && isObject(components.schemas) ? Object.entries(components.schemas) : [];
		for (const key of ['responses', 'parameters', 'requestBodies', 'headers', 'pathItems']) {
			const entries = components?.[key];
			if (isObject(entries) && Object.keys(entries).length) {
				fail(`#/components/${key}`, 'only components.schemas is supported');
			}
		}
		if (isObject(document.webhooks) && Object.keys(document.webhooks).length) {
			fail('#/webhooks', 'webhooks are not supported');
		}
		const schemaMembers = schemas.map(([name, schema]) =>
			property(name, this.schema(schema, child('#/components/schemas', name)), { doc: schema })
		);
		const componentMembers: Member[] = [
			property(
				'schemas',
				schemaMembers.length ? { kind: 'object', members: schemaMembers } : NEVER
			),
			...['responses', 'parameters', 'requestBodies', 'headers', 'pathItems'].map((key) =>
				property(key, NEVER)
			)
		];
		const declarations = [
			paths.length ? printInterface('paths', paths) : 'export type paths = Record<string, never>;',
			'export type webhooks = Record<string, never>;',
			components
				? printInterface('components', componentMembers)
				: 'export type components = Record<string, never>;',
			'export type $defs = Record<string, never>;',
			this.operations.length
				? printInterface('operations', this.operations)
				: 'export type operations = Record<string, never>;'
		];
		return `${HEADER}${declarations.join('\n')}\n`;
	}
}

// The TypeScript printer's parenthesization: a union or intersection inside an array, union or
// intersection gets parentheses.
function printType(type: TypeNode, indent: string): string {
	const nested = (inner: TypeNode) =>
		inner.kind === 'union' || inner.kind === 'intersection'
			? `(${printType(inner, indent)})`
			: printType(inner, indent);
	switch (type.kind) {
		case 'keyword':
			return type.name;
		case 'literal':
		case 'reference':
			return type.text;
		case 'array':
			return `${nested(type.element)}[]`;
		case 'union':
			return type.types.map(nested).join(' | ');
		case 'intersection':
			return type.types.map(nested).join(' & ');
		case 'object':
			return printMembers(type.members, indent);
	}
}

function printMembers(members: Member[], indent: string): string {
	if (!members.length) return '{}';
	const inner = `${indent}    `;
	const lines = members.map((member) => {
		if (member.kind === 'index') {
			return `${inner}[${member.parameter}: string]: ${printType(member.type, inner)};`;
		}
		const modifiers = member.readonly ? 'readonly ' : '';
		const optional = member.optional ? '?' : '';
		const line = `${inner}${modifiers}${propertyName(member.name)}${optional}: ${printType(member.type, inner)};`;
		// The printer indents a comment's continuation lines with the member.
		return member.doc ? `${inner}${member.doc.replace(/\n/g, `\n${inner}`)}\n${line}` : line;
	});
	return `{\n${lines.join('\n')}\n${indent}}`;
}

function printInterface(name: string, members: Member[]): string {
	return `export interface ${name} ${printMembers(members, '')}`;
}

export function generateApiTypes(document: Json): string {
	if (!isObject(document)) throw new Error('expected an OpenAPI document object');
	return new Generator(document).generate();
}

async function readSchema(source: string): Promise<Json> {
	if (/^https?:\/\//.test(source)) {
		const response = await fetch(source, { signal: AbortSignal.timeout(30_000) });
		if (!response.ok) throw new Error(`GET ${source} answered ${response.status}`);
		return (await response.json()) as Json;
	}
	return (await Bun.file(source).json()) as Json;
}

if (import.meta.main) {
	const [source, output] = process.argv.slice(2);
	if (!source || !output) {
		console.error('usage: bun scripts/openapi-types.ts <schema file or URL> <output .d.ts>');
		process.exit(2);
	}
	await Bun.write(output, generateApiTypes(await readSchema(source)));
	console.log(`${source} -> ${output}`);
}
