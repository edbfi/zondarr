// @vitest-environment node
// expected.d.ts is the verbatim output of `openapi-typescript@7.13.0 schema.json` (TypeScript
// 6.0.3), the generator scripts/openapi-types.ts replaces. Below the header the two must agree
// byte for byte; regenerate expected.d.ts only with that release.
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { generateApiTypes, HEADER } from './openapi-types';

const FIXTURES = resolve(import.meta.dirname, 'fixtures/openapi-types');
const UPSTREAM_HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

const fixture = () => JSON.parse(readFileSync(resolve(FIXTURES, 'schema.json'), 'utf8'));

function generate(schema: Record<string, unknown>) {
	return generateApiTypes({
		openapi: '3.1.0',
		info: { title: 't', version: '1' },
		...schema
	} as never);
}

describe('generateApiTypes', () => {
	it('matches openapi-typescript 7.13.0 below the header', () => {
		const upstream = readFileSync(resolve(FIXTURES, 'expected.d.ts'), 'utf8');
		expect(upstream.startsWith(UPSTREAM_HEADER)).toBe(true);
		const output = generateApiTypes(fixture());
		expect(output.startsWith(HEADER)).toBe(true);
		expect(output.slice(HEADER.length)).toBe(upstream.slice(UPSTREAM_HEADER.length));
	});

	it('prints empty roots as records', () => {
		expect(generate({ paths: {} })).toBe(
			`${HEADER}export type paths = Record<string, never>;
export type webhooks = Record<string, never>;
export type components = Record<string, never>;
export type $defs = Record<string, never>;
export type operations = Record<string, never>;
`
		);
	});

	it.each([
		['allOf', { allOf: [{ type: 'string' }] }],
		['discriminator', { oneOf: [], discriminator: { propertyName: 'kind' } }],
		['prefixItems', { type: 'array', prefixItems: [{ type: 'string' }] }],
		['patternProperties', { type: 'object', patternProperties: { '^x': { type: 'string' } } }],
		['$defs', { $defs: { A: { type: 'string' } } }]
	])('refuses schema keyword %s', (keyword, schema) => {
		expect(() => generate({ components: { schemas: { S: schema } } })).toThrow(
			`#/components/schemas/S: schema keyword ${keyword} is not supported`
		);
	});

	it('refuses constructs Litestar does not emit', () => {
		const operation = { operationId: 'Op', responses: {} };
		expect(() => generate({ webhooks: { hook: {} } })).toThrow('webhooks are not supported');
		expect(() => generate({ components: { responses: { R: {} } } })).toThrow(
			'only components.schemas is supported'
		);
		expect(() => generate({ paths: { '/a': { $ref: '#/x' } } })).toThrow(
			'path item $ref is not supported'
		);
		expect(() => generate({ paths: { '/a': { get: { responses: {} } } } })).toThrow(
			'get needs an operationId'
		);
		expect(() =>
			generate({ paths: { '/a': { get: operation }, '/b': { get: operation } } })
		).toThrow('duplicate operationId Op');
		expect(() =>
			generate({ paths: { '/a': { get: { ...operation, parameters: [{ $ref: '#/p' }] } } } })
		).toThrow('parameter $ref is not supported');
		expect(() =>
			generate({ components: { schemas: { S: { $ref: 'other.json#/components/schemas/S' } } } })
		).toThrow('external $ref other.json#/components/schemas/S is not supported');
		expect(() =>
			generate({ components: { schemas: { S: { $ref: '#/components/schemas/Missing' } } } })
		).toThrow('cannot resolve $ref #/components/schemas/Missing');
		expect(() => generateApiTypes({ swagger: '2.0' })).toThrow('expected an OpenAPI 3 document');
	});
});
